"""Build the capstone's ERP + scenario dataset from two existing synthetic sources.

Both sources are read strictly read-only. Neither source project is modified.

Source 1 - synthetic Salesforce/ERP sandbox
    SalesforceExtract/sandbox/data/sandbox.db
    Generated by that project's own sandbox/synth.py (seeded, PHI-free, all names
    and values invented). Supplies Contact / Account / Prescriptions__c / Asset
    records using real Salesforce *field names* with fully invented *values*.

Source 2 - synthetic Freshdesk ticket corpus
    PhotheraOnPremStack/ticket-generator/output/tickets_synthetic_1000.jsonl
    Generated by that project's generate_tickets.py. Subject and body text is
    template + slot-filled, never LLM-generated, and the requester identities are
    drawn from source 1's 300-identity pool.

What this script adds that neither source has: a device **hardware revision**.
The sandbox models an Asset but has no revision field, and the whole point of the
checkpoint is revision-sensitive retrieval. Revision is therefore derived from the
Asset's ERP InstallDate by an install-cohort rule (see REVISION_COHORTS). The rule
is deterministic, applied uniformly to every Asset, and documented in
docs/SYNTHETIC_DATA_DICTIONARY.md. It is a capstone-added fiction, not a field
that came from either source.

Usage:
    python scripts/build_dataset.py
"""

from __future__ import annotations

import json
import os
import re
import sqlite3
import sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
OUT_DIR = os.path.join(PROJECT, "data", "erp")

PROJECTS_ROOT = os.environ.get(
    "PYCHARM_PROJECTS_ROOT", os.path.expanduser(os.path.join("~", "PycharmProjects"))
)
SANDBOX_DB = os.path.join(
    PROJECTS_ROOT, "SalesforceExtract", "sandbox", "data", "sandbox.db"
)
TICKETS_JSONL = os.path.join(
    PROJECTS_ROOT, "PhotheraOnPremStack", "ticket-generator", "output",
    "tickets_synthetic_1000.jsonl",
)

# Hardware-revision cohorts, keyed on the Asset's ERP InstallDate.
# Capstone-added fiction; see module docstring.
REVISION_COHORTS = (
    ("A", "", "2022-01-01"),
    ("B", "2022-01-01", "2024-01-01"),
    ("C", "2024-01-01", "9999-12-31"),
)

# The three synthetic customers used by the demonstration, chosen because their
# Asset mix exercises every required case: one model at three revisions, one
# model with no procedure coverage at all, and a second covered model.
CAST_IDENTITY_IDS = (10, 22, 26)

# Capstone-authored, customer-voice. Used by the two no-power scenarios so that
# SCN-01 and SCN-02 ask semantically identical questions about devices that
# differ only in hardware revision.
NO_POWER_SYMPTOM = (
    "The unit is completely dead now - no lights at all, no fan noise, and the "
    "screen stays black when I flip the power switch."
)


def revision_for(install_date: str) -> str:
    for rev, lo, hi in REVISION_COHORTS:
        if lo <= install_date < hi:
            return rev
    return "A"


def connect_ro(path: str) -> sqlite3.Connection:
    if not os.path.exists(path):
        sys.exit(f"ERROR: synthetic source not found: {path}")
    con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    return con


def load_erp(con: sqlite3.Connection):
    customers, devices, orders = [], [], []

    for iid in CAST_IDENTITY_IDS:
        ident = con.execute(
            "select * from identity where identity_id=?", (iid,)
        ).fetchone()
        if ident is None:
            sys.exit(f"ERROR: identity {iid} missing from {SANDBOX_DB}")

        account_id = f"ACC-{iid:05d}"
        customers.append(
            OrderedDict(
                account_id=account_id,
                customer_name=ident["canonical_name"],
                customer_kind=ident["kind"],
                source_identity_id=iid,
                source_system="salesforce (synthetic sandbox)",
            )
        )

        for rec in con.execute(
            "select * from source_record where identity_id=? and record_type='Asset' "
            "order by record_id",
            (iid,),
        ):
            a = json.loads(rec["attrs"])
            devices.append(
                OrderedDict(
                    serial_number=a["SerialNumber"],
                    model=a["ProductCode"],
                    revision=revision_for(a["InstallDate"]),
                    revision_basis="derived_from_install_date_cohort",
                    product_family=a["ProductFamily"],
                    status=a["Status"],
                    install_date=a["InstallDate"],
                    last_meter_recal=a.get("Date_of_Last_Meter_Recal__c"),
                    account_id=account_id,
                    customer_name=ident["canonical_name"],
                    prescription_id=a.get("Prescription__c"),
                )
            )

        for rec in con.execute(
            "select * from source_record where identity_id=? "
            "and record_type='Prescriptions__c' order by record_id",
            (iid,),
        ):
            p = json.loads(rec["attrs"])
            orders.append(
                OrderedDict(
                    order_id=p["Name"],
                    account_id=account_id,
                    customer_name=ident["canonical_name"],
                    product_prescribed=p.get("Product_Prescribed__c"),
                    device_serial_number=p.get("Device_Serial_Number__c") or None,
                    order_date=p.get("Prescription_Date__c"),
                    phase=p.get("Prescription_Phase__c"),
                    distributor_status=p.get("Distributor_Status__c"),
                    integration_status=p.get("Integration_Status__c"),
                )
            )

    return customers, devices, orders


# Invented carriers. Deliberately not any real logistics company - the brief
# excludes carrier integrations, and this is a local fixture, not a client.
CARRIERS = ("Northbound Parcel", "Civic Courier")

SHIPMENT_STATES = {
    "Shipped": ("Delivered", "signed for at reception"),
    "Complete": ("Delivered", "left in a safe place"),
    "On Hold": ("Held at depot", "awaiting delivery instructions"),
    "New": ("Label created", "not yet collected"),
    "In Process": ("In transit", "at the regional sorting hub"),
    "Denied": ("Cancelled", "order did not proceed"),
}


def build_shipments(orders):
    """Derive a synthetic shipment per order, deterministically.

    The synthetic ERP has no shipment object, so this is a capstone-added
    fixture built from each order's distributor status. It exists so the agent
    has a fourth tool to choose between, and so an order-status question can be
    answered without touching the QMS corpus at all.
    """
    shipments = []
    for n, o in enumerate(orders):
        status = o.get("distributor_status") or "New"
        state, note = SHIPMENT_STATES.get(status, ("Label created", "pending"))
        digits = "".join(ch for ch in o["order_id"] if ch.isdigit())
        shipments.append(
            OrderedDict(
                tracking_number=f"NP{digits[:7]:0>7}{n:02d}",
                carrier=CARRIERS[n % len(CARRIERS)],
                order_id=o["order_id"],
                account_id=o["account_id"],
                customer_name=o["customer_name"],
                device_serial_number=o.get("device_serial_number"),
                status=state,
                last_scan=note,
                shipped_date=o.get("order_date"),
            )
        )
    return shipments


def load_ticket_templates(archetypes):
    """Return the first ticket of each requested archetype, deterministically."""
    wanted = set(archetypes)
    found = {}
    with open(TICKETS_JSONL, encoding="utf-8") as fh:
        for line in fh:
            t = json.loads(line)
            arch = t.get("archetype")
            if arch in wanted and arch not in found:
                found[arch] = t
                if len(found) == len(wanted):
                    break
    missing = wanted - set(found)
    if missing:
        sys.exit(f"ERROR: archetypes not found in corpus: {sorted(missing)}")
    return found


# The corpus slot-fills one of these product names into its templates
# (ticket-generator/distributions.json -> device_prescribed_options).
CORPUS_DEVICE_NAMES = (
    "Phothera 600-3D", "Phothera 100XL", "Phothera 200XL", "Phothera 100",
    "Phothera 200", "Phothera 400", "Phothera 600", "Aquex",
)
_DEVICE_RE = re.compile("|".join(re.escape(n) for n in CORPUS_DEVICE_NAMES))


def retarget(text: str, model: str) -> str:
    """Point a corpus ticket body or subject at the scenario's device model.

    Swaps the corpus' slot-filled product name for the cast device's ERP model
    code, so the customer message and the ERP record agree on what the device is.
    """
    return _DEVICE_RE.sub(model, text).strip()


def build_scenarios(devices):
    by_serial = {d["serial_number"]: d for d in devices}

    def dev(serial):
        if serial not in by_serial:
            sys.exit(f"ERROR: expected device {serial} not in cast")
        return by_serial[serial]

    tpl = load_ticket_templates(
        ["device_failed", "rma_broken_lamp", "general_question",
         "report_of_erythema", "order_status_shipping"]
    )

    specs = [
        dict(
            scenario_id="SCN-01",
            name="Successful grounded retrieval",
            expect="validation PASS, grounded on an approved Rev A procedure",
            serial="98148469",
            archetype="device_failed",
            include_serial=True,
            symptom=NO_POWER_SYMPTOM,
        ),
        dict(
            scenario_id="SCN-02",
            name="Wrong revision",
            expect="validation FAIL on revision; must not serve Rev A or Rev C steps",
            serial="68177-DV5",
            archetype="device_failed",
            include_serial=True,
            symptom=NO_POWER_SYMPTOM,
        ),
        dict(
            scenario_id="SCN-03",
            name="No applicable source",
            expect="abstain; no procedure exists for this model at any revision",
            serial="66383977",
            archetype="general_question",
            include_serial=True,
            symptom=(
                "It has started making a rattling noise and the session stops "
                "early. What should I be checking?"
            ),
        ),
        dict(
            scenario_id="SCN-04",
            name="Missing serial number",
            expect="device identity unconfirmed; ask for the serial, do not guess",
            serial="68177-DV5",
            archetype="rma_broken_lamp",
            include_serial=False,
            symptom=None,
        ),
        dict(
            scenario_id="SCN-05",
            name="Potential safety complaint",
            expect="safety gate fires before retrieval; escalate to a human",
            serial="38180-BM2",
            archetype="report_of_erythema",
            include_serial=True,
            symptom=(
                "There was also a burning smell coming from the unit and the "
                "casing was too hot to touch."
            ),
        ),
        dict(
            scenario_id="SCN-06",
            name="Order and shipment status",
            expect=("answered from ERP order and shipment tools; the QMS "
                    "corpus is not relevant and must not be searched"),
            serial="52385502",
            archetype="order_status_shipping",
            include_serial=True,
            symptom=None,
        ),
    ]

    scenarios = []
    for s in specs:
        d = dev(s["serial"])
        t = tpl[s["archetype"]]

        body = retarget(t["description"], d["model"])
        adapted = ["product-name slot retargeted to the cast device's ERP model"]

        if s["symptom"]:
            # Capstone-authored customer-voice sentence. The corpus archetypes
            # describe a generic failure; each scenario needs one specific
            # symptom for the semantic query to be meaningful.
            body = body.rstrip() + " " + s["symptom"]
            adapted.append("capstone-authored symptom sentence appended")

        if s["include_serial"]:
            body += f"\n\nSerial number: {d['serial_number']}"
            adapted.append("serial number appended")
        else:
            adapted.append("serial number deliberately withheld")

        scenarios.append(
            OrderedDict(
                scenario_id=s["scenario_id"],
                name=s["name"],
                expected_behaviour=s["expect"],
                customer_name=d["customer_name"],
                account_id=d["account_id"],
                device_serial_number=(
                    d["serial_number"] if s["include_serial"] else None
                ),
                device_model=d["model"],
                device_revision=d["revision"],
                subject=retarget(t["subject"], d["model"]),
                customer_message=body,
                provenance=OrderedDict(
                    source_ticket_id=t["id"],
                    source_archetype=t["archetype"],
                    source_file=(
                        "PhotheraOnPremStack/ticket-generator/output/"
                        "tickets_synthetic_1000.jsonl"
                    ),
                    adapted="; ".join(adapted),
                ),
            )
        )
    return scenarios


def write(name, payload):
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
        fh.write("\n")
    print(f"  wrote {os.path.relpath(path, PROJECT)}  ({len(payload)} records)")


def main():
    print("Reading synthetic sources (read-only)...")
    print(f"  {SANDBOX_DB}")
    print(f"  {TICKETS_JSONL}")

    con = connect_ro(SANDBOX_DB)
    customers, devices, orders = load_erp(con)
    con.close()

    scenarios = build_scenarios(devices)
    shipments = build_shipments(orders)

    print("\nWriting capstone dataset...")
    write("customers.json", customers)
    write("devices.json", devices)
    write("orders.json", orders)
    write("shipments.json", shipments)
    write("scenarios.json", scenarios)

    print("\nDevice inventory:")
    for d in devices:
        print(f"  {d['customer_name']:<16} {d['model']:<10} Rev {d['revision']}  "
              f"{d['serial_number']:<12} install {d['install_date']}")


if __name__ == "__main__":
    main()

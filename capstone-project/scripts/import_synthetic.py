"""Import the verified synthetic datasets into the capstone's local database.

Reads two existing synthetic sources, strictly read-only, and loads the
relevant records into `data/operations.db`. Neither source project is
modified and nothing outside these two files is touched.

  Source 1  SalesforceExtract/sandbox/data/sandbox.db
            Generated by that project's own seeded sandbox/synth.py. 300
            invented identities (100 patient / 100 physician / 100
            organization) with Contact / Account / Prescriptions__c / Asset
            records using real Salesforce field names and wholly invented
            values. Its own README and the parallel ArchivePortalV2
            views.py:64 confirm the non-'alpha' sandbox is the synthetic one.

  Source 2  PhotheraOnPremStack/ticket-generator/output/
            tickets_synthetic_1000.jsonl
            1,000 tickets whose subject and body text is template plus
            slot-filled, never LLM-generated, with requester identities drawn
            from source 1's identity pool.

Provenance is preserved: every imported row keeps its source identifier, and
`customers.source_system` records where it came from.

The import is idempotent. Running it twice produces the same database.
Operational records (cases, RMAs, shipments) are never touched by an import.

    python scripts/import_synthetic.py                 # import / refresh
    python scripts/import_synthetic.py --validate-only # checks, no writes
    python scripts/import_synthetic.py --reset         # drop source tables first
    python scripts/import_synthetic.py --tickets 1000  # pool size to import
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sqlite3
import sys

sys.path.insert(0, os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

from capstone_rag import config, store as store_mod  # noqa: E402

# Hardware-revision cohorts, keyed on the Asset's ERP InstallDate.
# This is a capstone-added INFERENCE: the synthetic ERP has no revision
# field. See config.REVISION_* and docs/SYNTHETIC_DATA_DICTIONARY.md.
REVISION_COHORTS = (("A", "", "2022-01-01"),
                    ("B", "2022-01-01", "2024-01-01"),
                    ("C", "2024-01-01", "9999-12-31"))

# Fictional e-mail domain. `.invalid` is reserved by RFC 2606 and can never
# resolve, so no address generated here can reach anyone.
EMAIL_DOMAIN = "example.invalid"


def revision_for(install_date: str) -> str:
    for rev, lo, hi in REVISION_COHORTS:
        if lo <= (install_date or "") < hi:
            return rev
    return "A"


REGISTER_PATH = os.path.join(config.DATA_DIR, "revision_register.json")


def load_register() -> dict:
    """The fictional revision verification register (rule RV-1)."""
    if not os.path.exists(REGISTER_PATH):
        return {}
    with open(REGISTER_PATH, encoding="utf-8") as fh:
        return json.load(fh).get("entries", {})


def revision_for_asset(asset: dict, register: dict):
    """Return (revision, status, basis) under fictional rule RV-1.

    An install-date cohort is an INFERENCE and is never promoted to verified
    on its own. Only the register verifies a revision.
    """
    serial = asset.get("SerialNumber")
    install = asset.get("InstallDate")
    inferred = revision_for(install) if install else None
    entry = register.get(serial)

    if entry:
        verified = entry.get("verified_revision")
        if inferred and verified and verified != inferred:
            # The controlled record and the install-date cohort disagree.
            # Neither is trusted; a human has to settle it.
            return (verified, config.REVISION_CONTRADICTORY,
                    f"register says {verified}, install-date cohort implies "
                    f"{inferred}")
        return (verified, config.REVISION_VERIFIED,
                f"revision register entry verified by "
                f"{entry.get('verified_by')} on {entry.get('verified_on')}")

    if not install:
        return (None, config.REVISION_MISSING,
                "no install date in ERP and no revision register entry")

    return (inferred, config.REVISION_INFERRED,
            "derived from install-date cohort only; not verified")


def fake_email(name: str, account_id: str) -> str:
    slug = re.sub(r"[^a-z]+", ".", (name or "customer").lower()).strip(".")
    return f"{slug}.{account_id[-4:]}@{EMAIL_DOMAIN}"


def connect_source(path):
    if not os.path.exists(path):
        sys.exit(f"ERROR: synthetic source not found: {path}")
    con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    return con


# ---------------------------------------------------------------- extract

def extract_customers(con) -> dict:
    """One customer row per identity, enriched from its Contact/Account."""
    out = {}
    for ident in con.execute("SELECT * FROM identity ORDER BY identity_id"):
        iid = ident["identity_id"]
        account_id = f"ACC-{iid:05d}"
        attrs = json.loads(ident["attrs"] or "{}")
        row = {
            "account_id": account_id,
            "customer_name": ident["canonical_name"],
            "customer_kind": ident["kind"],
            "date_of_birth": ident["dob"],
            "phone": None, "mobile_phone": None, "email": None,
            "street": None, "city": None, "state": None,
            "preferred_contact": None,
            "source_identity_id": iid,
            "source_system": "SalesforceExtract/sandbox (synthetic)",
        }
        out[iid] = (row, attrs)

    for rec in con.execute(
        "SELECT identity_id, record_type, attrs FROM source_record "
        "WHERE record_type IN ('Contact','Account')"
    ):
        iid = rec["identity_id"]
        if iid not in out:
            continue
        a = json.loads(rec["attrs"] or "{}")
        row = out[iid][0]
        row["phone"] = row["phone"] or a.get("Phone")
        row["mobile_phone"] = row["mobile_phone"] or a.get("MobilePhone")
        row["street"] = row["street"] or a.get("MailingStreet")
        row["city"] = row["city"] or a.get("MailingCity")
        row["state"] = row["state"] or a.get("MailingState") or a.get(
            "BillingState")
        row["preferred_contact"] = (row["preferred_contact"]
                                    or a.get("Preferred_Method_of_Contact__c"))
        row["date_of_birth"] = (row["date_of_birth"] or a.get("Birthdate")
                                or a.get("DOB__c"))

    final = {}
    for iid, (row, _attrs) in out.items():
        row["email"] = fake_email(row["customer_name"], row["account_id"])
        final[iid] = row
    return final


def extract_devices(con, customers: dict, register: dict) -> list:
    rows = []
    for rec in con.execute(
        "SELECT identity_id, attrs FROM source_record "
        "WHERE record_type='Asset' ORDER BY record_id"
    ):
        iid = rec["identity_id"]
        if iid not in customers:
            continue
        a = json.loads(rec["attrs"] or "{}")
        serial = a.get("SerialNumber")
        if not serial:
            continue
        revision, rev_status, rev_basis = revision_for_asset(a, register)
        rows.append({
            "serial_number": serial,
            "model": a.get("ProductCode"),
            "revision": revision,
            "revision_status": rev_status,
            "revision_basis": rev_basis,
            "product_family": a.get("ProductFamily"),
            "status": a.get("Status"),
            "install_date": a.get("InstallDate"),
            "last_meter_recal": a.get("Date_of_Last_Meter_Recal__c"),
            "account_id": customers[iid]["account_id"],
            "prescription_id": a.get("Prescription__c"),
        })
    return rows


def extract_orders(con, customers: dict) -> list:
    rows = []
    for rec in con.execute(
        "SELECT identity_id, attrs FROM source_record "
        "WHERE record_type='Prescriptions__c' ORDER BY record_id"
    ):
        iid = rec["identity_id"]
        if iid not in customers:
            continue
        p = json.loads(rec["attrs"] or "{}")
        rows.append({
            "order_id": p.get("Name"),
            "account_id": customers[iid]["account_id"],
            "product_prescribed": p.get("Product_Prescribed__c"),
            "device_serial_number": p.get("Device_Serial_Number__c") or None,
            "order_date": p.get("Prescription_Date__c"),
            "phase": p.get("Prescription_Phase__c"),
            "distributor_status": p.get("Distributor_Status__c"),
            "integration_status": p.get("Integration_Status__c"),
        })
    return [r for r in rows if r["order_id"]]


CARRIERS = ("Northbound Parcel", "Civic Courier")
SHIPMENT_STATES = {
    "Shipped": ("Delivered", "signed for at reception"),
    "Complete": ("Delivered", "left in a safe place"),
    "On Hold": ("Held at depot", "awaiting delivery instructions"),
    "New": ("Label created", "not yet collected"),
    "In Process": ("In transit", "at the regional sorting hub"),
    "Denied": ("Cancelled", "order did not proceed"),
}


def derive_shipments(orders: list) -> list:
    rows = []
    for n, o in enumerate(orders):
        state, note = SHIPMENT_STATES.get(
            o.get("distributor_status") or "New", ("Label created", "pending"))
        digits = "".join(ch for ch in o["order_id"] if ch.isdigit())
        rows.append({
            "tracking_number": f"NP{digits[:7]:0>7}{n:04d}",
            "carrier": CARRIERS[n % len(CARRIERS)],
            "order_id": o["order_id"],
            "account_id": o["account_id"],
            "device_serial_number": o.get("device_serial_number"),
            "status": state, "last_scan": note,
            "shipped_date": o.get("order_date"),
        })
    return rows


CORPUS_DEVICE_NAMES = ("Phothera 600-3D", "Phothera 100XL", "Phothera 200XL",
                       "Phothera 100", "Phothera 200", "Phothera 400",
                       "Phothera 600", "Aquex")
_DEVICE_RE = re.compile("|".join(re.escape(n) for n in CORPUS_DEVICE_NAMES))


def _identification_mix(source_ticket_id: int) -> tuple:
    """Deterministically decide what identification a given e-mail carries.

    Real inbound mail is uneven: some customers quote their serial number,
    some just sign their name, some neither. The mix matters because it is
    what makes two-point verification a real gate in the demonstration
    rather than something that always passes or always fails.

    Returns (include_name, include_serial, include_dob).
    """
    h = hashlib.sha1(f"idmix::{source_ticket_id}".encode()).hexdigest()
    bucket = int(h[:4], 16) % 10
    if bucket < 5:          # 50% - name and serial  -> verifies on two points
        return True, True, False
    if bucket < 7:          # 20% - name and DOB     -> verifies on two points
        return True, False, True
    if bucket < 9:          # 20% - name only        -> needs one more point
        return True, False, False
    return False, True, False   # 10% - serial only  -> needs one more point


def extract_tickets(path, customers: dict, devices_by_account: dict,
                    limit: int) -> list:
    rows = []
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh):
            if n >= limit:
                break
            t = json.loads(line)
            iid = t.get("synthetic_identity_id")
            cust = customers.get(iid)
            account_id = cust["account_id"] if cust else None
            owned = devices_by_account.get(account_id, [])
            # Bind the ticket to a device the requester actually owns, so the
            # ERP join is real rather than decorative.
            serial = owned[0]["serial_number"] if owned else None
            model = owned[0]["model"] if owned else None
            subject = t.get("subject") or ""
            body = t.get("description") or ""
            if model:
                subject = _DEVICE_RE.sub(model, subject)
                body = _DEVICE_RE.sub(model, body)

            # Add the identification the customer would have supplied. The
            # corpus bodies carry none, so without this every case would
            # fail verification for the same uninteresting reason.
            if cust:
                want_name, want_serial, want_dob = _identification_mix(
                    t.get("id") or n)
                extra = []
                if want_serial and serial:
                    extra.append(f"Serial number: {serial}")
                if want_dob and cust.get("date_of_birth"):
                    extra.append(f"Date of birth: {cust['date_of_birth']}")
                if extra:
                    body = body.rstrip() + "\n\n" + "\n".join(extra)
                if want_name:
                    body = body.rstrip() + f"\n\nThanks,\n{cust['customer_name']}"
            rows.append({
                "pool_id": f"POOL-{t['id']}",
                "source_ticket_id": t.get("id"),
                "archetype": t.get("archetype"),
                "subject": subject,
                "body": body,
                "product": t.get("product"),
                "source_identity_id": iid,
                "account_id": account_id,
                "device_serial_number": serial,
                "created_at": t.get("created_at"),
                "tags": json.dumps(t.get("tags") or []),
                "released": 0,
            })
    return rows


# --------------------------------------------------------------- validate

def validate(customers, devices, orders, shipments, tickets) -> list:
    """Schema, join integrity, missing values, duplicates."""
    problems = []

    def dup(rows, key, label):
        seen, dups = set(), set()
        for r in rows:
            v = r[key]
            if v in seen:
                dups.add(v)
            seen.add(v)
        if dups:
            problems.append(
                f"{label}: {len(dups)} duplicate {key} value(s), e.g. "
                f"{sorted(dups)[:3]}")

    cust_rows = list(customers.values())
    dup(cust_rows, "account_id", "customers")
    dup(devices, "serial_number", "devices")
    dup(orders, "order_id", "orders")
    dup(shipments, "tracking_number", "shipments")
    dup(tickets, "pool_id", "ticket_pool")

    accounts = {c["account_id"] for c in cust_rows}
    orphan_dev = [d["serial_number"] for d in devices
                  if d["account_id"] not in accounts]
    if orphan_dev:
        problems.append(f"devices: {len(orphan_dev)} with no customer")
    orphan_ord = [o["order_id"] for o in orders if o["account_id"] not in accounts]
    if orphan_ord:
        problems.append(f"orders: {len(orphan_ord)} with no customer")

    serials = {d["serial_number"] for d in devices}
    bad_order_serial = [o["order_id"] for o in orders
                        if o["device_serial_number"]
                        and o["device_serial_number"] not in serials]
    if bad_order_serial:
        problems.append(
            f"orders: {len(bad_order_serial)} reference an unknown serial")

    unbound = [t["pool_id"] for t in tickets if not t["account_id"]]
    if unbound:
        problems.append(
            f"ticket_pool: {len(unbound)} tickets could not be bound to a "
            f"customer (requester identity not in the pool)")

    no_dob = [c["account_id"] for c in cust_rows if not c["date_of_birth"]]
    no_phone = [c["account_id"] for c in cust_rows if not c["phone"]]
    missing_rev = [d["serial_number"] for d in devices
                   if d["revision_status"] == config.REVISION_MISSING]
    contradictory = [d["serial_number"] for d in devices
                     if d["revision_status"] == config.REVISION_CONTRADICTORY]

    return problems, {
        "customers_without_dob": len(no_dob),
        "customers_without_phone": len(no_phone),
        "devices_revision_missing": len(missing_rev),
        "devices_revision_contradictory": len(contradictory),
        "tickets_unbound": len(unbound),
    }


# ------------------------------------------------------------------ main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=None)
    ap.add_argument("--tickets", type=int, default=1000)
    ap.add_argument("--validate-only", action="store_true")
    ap.add_argument("--reset", action="store_true",
                    help="clear source tables before importing")
    args = ap.parse_args()

    print("Reading synthetic sources (read-only)")
    print(f"  {config.SANDBOX_DB}")
    print(f"  {config.TICKETS_JSONL}")
    con = connect_source(config.SANDBOX_DB)

    register = load_register()
    if not register:
        print("\n  WARNING: no revision register found at "
              f"{REGISTER_PATH}\n  every device revision will be treated as "
              "INFERRED. Run scripts/build_revision_register.py first.")
    else:
        print(f"  revision register: {len(register)} verified entries")

    customers = extract_customers(con)
    devices = extract_devices(con, customers, register)
    orders = extract_orders(con, customers)
    con.close()
    shipments = derive_shipments(orders)

    by_account = {}
    for d in devices:
        by_account.setdefault(d["account_id"], []).append(d)

    tickets = extract_tickets(config.TICKETS_JSONL, customers, by_account,
                              args.tickets)

    print("\nExtracted")
    print(f"  customers   {len(customers)}")
    print(f"  devices     {len(devices)}")
    print(f"  orders      {len(orders)}")
    print(f"  shipments   {len(shipments)}")
    print(f"  tickets     {len(tickets)}")

    problems, counts = validate(customers, devices, orders, shipments, tickets)
    print("\nValidation")
    for k, v in counts.items():
        print(f"  {k:<34} {v}")
    if problems:
        print("\n  PROBLEMS:")
        for p in problems:
            print(f"    - {p}")
    else:
        print("  no integrity problems found")

    rev_counts = {}
    for d in devices:
        rev_counts[d["revision_status"]] = rev_counts.get(
            d["revision_status"], 0) + 1
    print(f"\n  revision provenance: {rev_counts}")

    if args.validate_only:
        print("\n--validate-only: nothing written")
        return 0

    st = store_mod.Store(args.db) if args.db else store_mod.get_store()
    if args.reset:
        for t in ("ticket_pool", "source_shipments", "orders", "devices",
                  "customers"):
            st.execute(f"DELETE FROM {t}")
        print("\nsource tables cleared")

    print("\nWriting to", st.path)
    for row in customers.values():
        st.upsert("customers", row, "account_id")
    for row in devices:
        st.upsert("devices", row, "serial_number")
    for row in orders:
        st.upsert("orders", row, "order_id")
    for row in shipments:
        st.upsert("source_shipments", row, "tracking_number")
    for row in tickets:
        # Preserve `released` across re-imports so a re-run does not resurrect
        # tickets the simulator has already delivered.
        existing = st.one("SELECT released FROM ticket_pool WHERE pool_id=?",
                          (row["pool_id"],))
        if existing:
            row["released"] = existing["released"]
        st.upsert("ticket_pool", row, "pool_id")

    st.audit("synthetic_data_imported", actor="import_script",
             summary=f"{len(customers)} customers, {len(devices)} devices, "
                     f"{len(tickets)} pooled tickets",
             detail={"counts": counts, "problems": problems,
                     "revision_provenance": rev_counts})

    print("\nStore contents")
    for k, v in st.stats().items():
        print(f"  {k:<24} {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

import {mkdir,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)('playwright');
const out='docs/phase4_2/screenshots';await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8767/pressure-testing');
await page.getByRole('button',{name:'Experiments',exact:true}).click();
await page.getByRole('button',{name:'Preview run count',exact:true}).waitFor();
await page.getByLabel('Baseline · local Qwen3 4B',{exact:true}).uncheck();
await page.getByLabel('Synthetic phone-log acceptance',{exact:true}).check();
const scenarios=page.locator('.experiment-form .check-options').nth(1);
for(const checkbox of await scenarios.locator('input[type=checkbox]').all())await checkbox.uncheck();
await scenarios.getByRole('checkbox',{name:/phone-log/}).check();
await page.getByLabel('Campaign duration seconds').fill('30');
await page.getByLabel('Repetitions',{exact:true}).fill('1');
await page.getByRole('button',{name:'Preview run count',exact:true}).click();
await page.getByRole('button',{name:'Start isolated experiment',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.experiment-form')&&Array.from(document.querySelectorAll('h2')).some(e=>e.textContent==='Small comparison'));
await page.screenshot({path:out+'/lab-duration-controls.png',fullPage:true});
await page.getByRole('button',{name:'Cluster & telemetry',exact:true}).click();
await page.getByRole('button',{name:'Save enrollment settings'}).waitFor();
await page.screenshot({path:out+'/cluster-controls.png',fullPage:true});
await page.goto('http://127.0.0.1:8767/agent-arena?view=node&selection=head-192-0-2-6');
await page.waitForFunction(()=>document.querySelector('#connection')?.textContent.includes('sequence'));
await page.screenshot({path:out+'/recorded-distributed-node6.png',fullPage:false});
await writeFile('docs/phase4_2/visual_acceptance.json',JSON.stringify({coordinator_loopback_only:true,remote_desktop_verified:false,page_errors:errors},null,2));
await browser.close();if(errors.length)throw Error(errors.join('\n'));
console.log('Lab, cluster and recorded remote inference Arena screens captured without page errors.');

                    found.Add(new LegacyArtifact { Kind = Path.GetFileName(d).Equals("browser-profile", StringComparison.OrdinalIgnoreCase) ? "browser-profile" : "directory", Detail = d, Owned = Path.GetFileName(d).Equals("browser-profile", StringComparison.OrdinalIgnoreCase) });
            }
            if (File.Exists(StartupLink)) found.Add(new LegacyArtifact { Kind = "startup-shortcut", Detail = StartupLink, Owned = ShortcutTargetsLegacy(StartupLink) });
            var xml = TaskXml();
            if (xml != null) found.Add(new LegacyArtifact { Kind = "scheduled-task", Detail = TaskName, Owned = xml.IndexOf("Capstone-Arena-Viewer", StringComparison.OrdinalIgnoreCase) >= 0 });
            foreach (var p in Processes())
                found.Add(new LegacyArtifact { Kind = p.Item2, Detail = "PID " + p.Item1, Owned = true });
            return found;
        }
        static bool ShortcutTargetsLegacy(string lnk)
        {
            try { var text = Encoding.Unicode.GetString(File.ReadAllBytes(lnk)) + Encoding.ASCII.GetString(File.ReadAllBytes(lnk)); return text.IndexOf("Capstone-Arena-Viewer", StringComparison.OrdinalIgnoreCase) >= 0; }
            catch { return false; }
        }
        public static string TaskXml()
        {
            try
            {
                var psi = new ProcessStartInfo("schtasks.exe", "/Query /TN \"" + TaskName + "\" /XML") { UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true };
                using (var p = Process.Start(psi)) { var o = p.StandardOutput.ReadToEnd(); p.WaitForExit(10000); return p.ExitCode == 0 ? o : null; }
            }
            catch { return null; }
        }
        /// <summary>(pid, kind) for the legacy watchdog and the Edge windows using its profile.</summary>
        public static List<Tuple<int, string>> Processes()
        {
            var list = new List<Tuple<int, string>>();
            try
            {
                using (var s = new ManagementObjectSearcher("SELECT ProcessId, Name, CommandLine FROM Win32_Process WHERE Name='powershell.exe' OR Name='msedge.exe' OR Name='pwsh.exe'"))
                    foreach (ManagementObject o in s.Get())
                    {
                        var cmd = Convert.ToString(o["CommandLine"]) ?? "";
                        if (cmd.IndexOf("Capstone-Arena-Viewer", StringComparison.OrdinalIgnoreCase) < 0) continue;
                        var name = Convert.ToString(o["Name"]).ToLowerInvariant();
                        if (name == "msedge.exe" && cmd.IndexOf("browser-profile", StringComparison.OrdinalIgnoreCase) >= 0) list.Add(Tuple.Create(Convert.ToInt32(o["ProcessId"]), "legacy-edge"));
                        else if (name != "msedge.exe" && cmd.IndexOf("Viewer.ps1", StringComparison.OrdinalIgnoreCase) >= 0) list.Add(Tuple.Create(Convert.ToInt32(o["ProcessId"]), "legacy-watchdog"));
                    }
            }
            catch (Exception ex) { Log.Error("legacy process scan failed: " + ex.Message); }
            return list;
        }

        /// <summary>Remove only proven-owned legacy artifacts. Returns a human-readable action list.</summary>
        public static List<string> Retire(bool deleteBrowserData)
        {
            var done = new List<string>();
            foreach (var p in Processes().Where(x => x.Item2 == "legacy-watchdog"))
                try { Process.GetProcessById(p.Item1).Kill(); done.Add("stopped legacy viewer watchdog PID " + p.Item1); } catch { }
            System.Threading.Thread.Sleep(500);
            foreach (var p in Processes().Where(x => x.Item2 == "legacy-edge"))
                try { Process.GetProcessById(p.Item1).CloseMainWindow(); } catch { }
            System.Threading.Thread.Sleep(1500);
            foreach (var p in Processes().Where(x => x.Item2 == "legacy-edge"))
                try { Process.GetProcessById(p.Item1).Kill(); done.Add("closed legacy viewer Edge window PID " + p.Item1); } catch { }
            if (File.Exists(StartupLink) && ShortcutTargetsLegacy(StartupLink)) { File.Delete(StartupLink); done.Add("removed legacy Startup shortcut"); }
            var xml = TaskXml();
            if (xml != null && xml.IndexOf("Capstone-Arena-Viewer", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                var psi = new ProcessStartInfo("schtasks.exe", "/Delete /TN \"" + TaskName + "\" /F") { UseShellExecute = false, CreateNoWindow = true };
                using (var p = Process.Start(psi)) p.WaitForExit(10000);
                if (TaskXml() == null) done.Add("removed legacy scheduled task " + TaskName); else done.Add("WARNING: could not remove scheduled task " + TaskName);
            }
            if (Directory.Exists(Paths.LegacyDir))
            {
                foreach (var name in OwnedFiles)
                {
                    var f = Path.Combine(Paths.LegacyDir, name);
                    if (File.Exists(f)) { File.Delete(f); done.Add("removed legacy file " + name); }
                }
                var profile = Path.Combine(Paths.LegacyDir, "browser-profile");
                if (deleteBrowserData && Directory.Exists(profile)) { Directory.Delete(profile, true); done.Add("deleted legacy viewer browser data"); }
                if (!Directory.EnumerateFileSystemEntries(Paths.LegacyDir).Any()) { Directory.Delete(Paths.LegacyDir); done.Add("removed empty legacy folder"); }
                else done.Add("kept " + Paths.LegacyDir + " (contains files this installer does not own, or kept browser data)");
            }
            return done;
        }
    }

    public static class Startup
    {
        // Tests use a private key so they never register real sign-in startup.
        static string RunKey { get { return Paths.Testing ? @"Software\AgentArenaTest\Run" : @"Software\Microsoft\Windows\CurrentVersion\Run"; } }
        public static string Current()
        {
            using (var k = Registry.CurrentUser.OpenSubKey(RunKey)) return k == null ? null : k.GetValue(Product.RunValue) as string;
        }
        public static void Enable(string exe)
        {
            using (var k = Registry.CurrentUser.CreateSubKey(RunKey)) k.SetValue(Product.RunValue, "\"" + exe + "\" --background");
        }
        public static void Disable()
        {
            using (var k = Registry.CurrentUser.OpenSubKey(RunKey, true)) if (k != null && k.GetValue(Product.RunValue) != null) k.DeleteValue(Product.RunValue);
        }
    }


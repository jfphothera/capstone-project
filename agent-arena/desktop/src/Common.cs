    /// <summary>arena.v2 client: HMAC-signed requests, signed responses verified.</summary>
    public class ArenaClient
    {
        public readonly string BaseUrl, CredentialId;
        readonly byte[] key;
        public ArenaClient(string baseUrl, string credentialId, string secret)
        {
            BaseUrl = baseUrl.TrimEnd('/'); CredentialId = credentialId; key = DeriveKey(secret);
        }
        public static byte[] DeriveKey(string secret) { using (var h = new HMACSHA256(Encoding.UTF8.GetBytes(secret))) return h.ComputeHash(Encoding.ASCII.GetBytes("arena.v2")); }
        public static string B64u(byte[] b) { return Convert.ToBase64String(b).TrimEnd('=').Replace('+', '-').Replace('/', '_'); }
        public static byte[] UnB64u(string s) { s = s.Replace('-', '+').Replace('_', '/'); return Convert.FromBase64String(s + new string('=', (4 - s.Length % 4) % 4)); }
        static string Sha256Hex(byte[] data) { using (var s = SHA256.Create()) return BitConverter.ToString(s.ComputeHash(data)).Replace("-", "").ToLowerInvariant(); }
        static byte[] Hmac(byte[] k, byte[] m) { using (var h = new HMACSHA256(k)) return h.ComputeHash(m); }

        // Field defect D2 diagnosis: where a slow request spends its time. The bind callback runs on the
        // calling thread just before a new TCP connection is opened, so time before it is client-side
        // (proxy, name lookup); time after it is connect, network and the service.
        const long SlowMs = 2000;
        [ThreadStatic] static Stopwatch bindWatch;
        [ThreadStatic] static long bindAt;
        static IPEndPoint OnBind(ServicePoint point, IPEndPoint remote, int retry) { if (bindWatch != null && bindAt < 0) bindAt = bindWatch.ElapsedMilliseconds; return null; }
        static Stopwatch StartTiming(HttpWebRequest req) { req.ServicePoint.BindIPEndPointDelegate = OnBind; bindWatch = Stopwatch.StartNew(); bindAt = -1; return bindWatch; }
        static void Timing(string method, string url, Stopwatch watch, long sent, long headers, string outcome)
        {
            var total = watch.ElapsedMilliseconds; var connect = bindAt; bindWatch = null;
            var wait = System.Text.RegularExpressions.Regex.Match(url, @"[?&]wait=(\d+)");
            var expected = wait.Success ? long.Parse(wait.Groups[1].Value) * 1000 : 0;   // a long-poll may legitimately wait
            if (total - expected < SlowMs && url.IndexOf("/v2/enroll", StringComparison.Ordinal) < 0) return;
            Log.Write(total - expected >= SlowMs ? "WARN" : "INFO", "request timing " + method + " " + url + ": " + outcome + " after " + total + " ms; " +
                (connect >= 0 ? "new connection started at " + connect + " ms" : "reused connection (or connect not observed)") +
                (sent >= 0 ? ", request sent at " + sent + " ms" : "") + (headers >= 0 ? ", response headers at " + headers + " ms" : ""));
        }

        public string Request(string method, string target, string jsonBody, int timeoutSeconds)
        {
            var body = jsonBody == null ? new byte[0] : Encoding.UTF8.GetBytes(jsonBody);
            var stamp = ((long)(DateTime.UtcNow - new DateTime(1970, 1, 1)).TotalSeconds).ToString();
            var nonceBytes = new byte[16]; using (var rng = RandomNumberGenerator.Create()) rng.GetBytes(nonceBytes);
            var nonce = B64u(nonceBytes);
            var path = new Uri(BaseUrl).AbsolutePath.TrimEnd('/') + target;
            var canonical = string.Join("\n", new[] { method.ToUpperInvariant(), path, stamp, nonce, Sha256Hex(body) });
            var req = (HttpWebRequest)WebRequest.Create(BaseUrl + target);
            req.Method = method; req.Timeout = req.ReadWriteTimeout = timeoutSeconds * 1000; req.Proxy = null; req.KeepAlive = true;
            req.Headers["X-Arena-Credential"] = CredentialId; req.Headers["X-Arena-Timestamp"] = stamp; req.Headers["X-Arena-Nonce"] = nonce;
            req.Headers["X-Arena-Signature"] = B64u(Hmac(key, Encoding.UTF8.GetBytes(canonical)));
            req.ContentType = "application/json";
            var watch = StartTiming(req); long sent = -1, headers;
            HttpWebResponse resp;
            try
            {
                if (method == "POST") { req.ContentLength = body.Length; using (var s = req.GetRequestStream()) s.Write(body, 0, body.Length); sent = watch.ElapsedMilliseconds; }
                try { resp = (HttpWebResponse)req.GetResponse(); }
                catch (WebException ex) { resp = ex.Response as HttpWebResponse; if (resp == null) throw; }
            }
            catch (WebException ex) { Timing(method, target, watch, sent, -1, "failed (" + ex.Status + ")"); throw; }
            headers = watch.ElapsedMilliseconds;
            using (resp)
            {
                byte[] raw; using (var ms = new MemoryStream()) { resp.GetResponseStream().CopyTo(ms); raw = ms.ToArray(); }
                var status = (int)resp.StatusCode; var signature = resp.Headers["X-Arena-Response-Signature"];
                Timing(method, target, watch, sent, headers, "HTTP " + status);
                var expected = B64u(Hmac(key, Encoding.UTF8.GetBytes(status + "\n" + nonce + "\n" + Sha256Hex(raw))));
                if (signature == null || !CryptographicEquals(signature, expected))
                {
                    // The service cannot sign a refusal for a credential it does not know. Nothing from this
                    // response is used; a successful answer must still be signed.
                    if (status == 401 || status == 403)
                        throw new ArenaException(status, "refused", "The service refused this credential (unknown, revoked, expired or already used)");
                    throw new ArenaException(502, "service_identity", "Response is not signed by the Arena Event Service for this credential");
                }
                var text = Encoding.UTF8.GetString(raw);
                if (status >= 400) { var d = SafeParse(text); throw new ArenaException(status, Json.Str(d, "error") ?? "error", Json.Str(d, "message") ?? ""); }
                return text;
            }
        }
        static Dictionary<string, object> SafeParse(string t) { try { return Json.Parse(t); } catch { return new Dictionary<string, object>(); } }
        static bool CryptographicEquals(string a, string b)
        {
            if (a.Length != b.Length) return false; int diff = 0;
            for (int i = 0; i < a.Length; i++) diff |= a[i] ^ b[i];
            return diff == 0;
        }

        public static string NormalizeCode(string code)
        {
            var raw = new string(code.ToUpperInvariant().Where(char.IsLetterOrDigit).ToArray());
            if (raw.StartsWith("ARENA")) raw = raw.Substring(5);
            var groups = new List<string>(); for (int i = 0; i < raw.Length; i += 4) groups.Add(raw.Substring(i, Math.Min(4, raw.Length - i)));
            return "ARENA-" + string.Join("-", groups);
        }
        public byte[] Unseal(string token)
        {
            var raw = UnB64u(token);
            var nonce = raw.Take(16).ToArray(); var tag = raw.Skip(raw.Length - 32).ToArray(); var cipher = raw.Skip(16).Take(raw.Length - 48).ToArray();
            var enc = Hmac(key, Encoding.ASCII.GetBytes("seal-enc")); var mac = Hmac(key, Encoding.ASCII.GetBytes("seal-mac"));
            if (!CryptographicEquals(B64u(tag), B64u(Hmac(mac, nonce.Concat(cipher).ToArray())))) throw new CryptographicException("sealed payload failed authentication");
            var stream = new List<byte>(); int counter = 0;
            while (stream.Count < cipher.Length) { var c = BitConverter.GetBytes(counter++); Array.Reverse(c); stream.AddRange(Hmac(enc, nonce.Concat(c).ToArray())); }
            var plain = new byte[cipher.Length]; for (int i = 0; i < cipher.Length; i++) plain[i] = (byte)(cipher[i] ^ stream[i]);
            return plain;
        }
        /// <summary>Exchange a one-time code for a viewer credential. Returns the service response.</summary>
        public static Dictionary<string, object> Enroll(string baseUrl, string displayId, string code, out string credentialId, out string secret)
        {
            var client = new ArenaClient(baseUrl, "enroll:" + displayId, NormalizeCode(code));
            Dictionary<string, object> response;
            try { response = Json.Parse(client.Request("POST", "/v2/enroll", Json.Write(new Dictionary<string, object> { { "machine_hash", Identity.MachineHash() } }), 30)); }
            catch (ArenaException ex)
            {
                if (ex.Code != "refused") throw;
                throw new ArenaException(ex.Status, "code_refused", "the code for " + displayId + " was refused: already used, expired, replaced by a newer code, or issued for a different display");
            }
            credentialId = Json.Str(response, "credential_id");
            secret = Encoding.UTF8.GetString(client.Unseal(Json.Str(response, "sealed_secret")));
            return response;
        }
        static string Get(string url, int timeoutSeconds)
        {
            var req = (HttpWebRequest)WebRequest.Create(url);
            req.Timeout = req.ReadWriteTimeout = timeoutSeconds * 1000; req.Proxy = null; req.KeepAlive = false;
            var watch = StartTiming(req); var path = new Uri(url).PathAndQuery;
            HttpWebResponse resp;
            try { resp = (HttpWebResponse)req.GetResponse(); }
            catch (WebException ex) { Timing("GET", path, watch, -1, -1, ex.Response != null ? "HTTP error" : "failed (" + ex.Status + ")"); throw; }
            var headers = watch.ElapsedMilliseconds;
            using (resp) using (var r = new StreamReader(resp.GetResponseStream())) { var text = r.ReadToEnd(); Timing("GET", path, watch, -1, headers, "HTTP " + (int)resp.StatusCode); return text; }
        }
        public static Dictionary<string, object> Health(string baseUrl, int timeoutSeconds)
        {
            // One retry when nothing answered: a first request on the isolated LAN can stall (field defect D2).
            var url = baseUrl.TrimEnd('/') + "/v2/health";
            try { return Json.Parse(Get(url, timeoutSeconds)); }
            catch (WebException ex) { if (ex.Response != null) throw; Log.Info("health check " + url + " got no answer (" + ex.Status + "); retrying once"); }
            return Json.Parse(Get(url, timeoutSeconds));
        }
        /// <summary>Unauthenticated registry hint for the caller's own address. Null, with a reason, when unavailable.</summary>
        public static Dictionary<string, object> WhoAmI(string baseUrl, int timeoutSeconds, out string reason)
        {
            reason = null;
            try { return Json.Parse(Get(baseUrl.TrimEnd('/') + "/v2/whoami", timeoutSeconds)); }
            catch (WebException ex)
            {
                if (ex.Response != null) { ex.Response.Close(); reason = "this event service has no registry lookup (older than 2.1)"; }
                else reason = "not reachable (" + ex.Message + ")";
            }
            catch (Exception ex) { reason = "unreadable registry answer (" + ex.Message + ")"; }
            return null;
        }
    }

    public class Candidate { public string Address, Interface, DisplayId, Role, Reason; }

    /// <summary>Proposes this machine's display identity. Never authorizes: enrollment does.</summary>
    public static class Identity
    {
        public static string MachineHash()
        {
            string guid = "unknown";
            try
            {
                using (var k = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, RegistryView.Registry64).OpenSubKey(@"SOFTWARE\Microsoft\Cryptography"))
                    if (k != null) guid = Convert.ToString(k.GetValue("MachineGuid"));
            }
            catch { }
            using (var s = SHA256.Create()) return BitConverter.ToString(s.ComputeHash(Encoding.UTF8.GetBytes(guid + "|agent-arena"))).Replace("-", "").ToLowerInvariant();
        }
        public static List<Tuple<string, string, string>> LocalAddresses()
        {
            var result = new List<Tuple<string, string, string>>();
            foreach (var nic in NetworkInterface.GetAllNetworkInterfaces())
                foreach (var ua in nic.GetIPProperties().UnicastAddresses)
                    if (ua.Address.AddressFamily == AddressFamily.InterNetwork && !IPAddress.IsLoopback(ua.Address))
                        result.Add(Tuple.Create(ua.Address.ToString(), nic.Name, nic.OperationalStatus.ToString()));
            return result;
        }
        static bool InNetwork(string address, string cidr)
        {
            var parts = cidr.Split('/'); var bits = int.Parse(parts[1]);
            var a = BitConverter.ToUInt32(IPAddress.Parse(address).GetAddressBytes().Reverse().ToArray(), 0);
            var n = BitConverter.ToUInt32(IPAddress.Parse(parts[0]).GetAddressBytes().Reverse().ToArray(), 0);
            var mask = bits == 0 ? 0u : uint.MaxValue << (32 - bits);
            if ((a & mask) != (n & mask)) return false;
            var host = a & ~mask; return host != 0 && host != ~mask;
        }
        public static List<Candidate> Candidates(DeploymentConfig config)
        {
            var list = new List<Candidate>();
            foreach (var t in LocalAddresses())
            {
                if (t.Item3 != "Up" || t.Item1.StartsWith("169.254.")) continue;
                if (config.OrchestratorDisplays.ContainsKey(t.Item1))
                    list.Add(new Candidate { Address = t.Item1, Interface = t.Item2, Role = "orchestrator", DisplayId = config.OrchestratorDisplays[t.Item1], Reason = "registered orchestrator display address" });
                else if (config.ExcludeAddresses.Contains(t.Item1)) continue;
                else if (config.DisplayNetworks.Any(n => InNetwork(t.Item1, n)))
                    list.Add(new Candidate { Address = t.Item1, Interface = t.Item2, Role = "head", DisplayId = "head-" + t.Item1.Replace('.', '-'), Reason = "address in an authorized display network" });
            }
            return list;
        }
        /// <summary>The event service endpoints to ask: the installed (possibly migrated) ones first, else the package's.</summary>
        public static List<string> Endpoints(DeploymentConfig config)
        {
            try { var cfg = LocalConfig.Load(); if (cfg != null && cfg.Endpoints.Count > 0) return cfg.Endpoints; } catch { }
            return config == null ? new List<string>() : config.Endpoints;
        }
        /// <summary>
        /// Proposes identities from the event service registry for this computer's address, so heads and
        /// orchestrator displays at any registered address are recognised without rebuilding the package.
        /// Falls back to the package's network convention only when the registry cannot be asked.
        /// </summary>
        public static List<Candidate> Resolve(DeploymentConfig config, IList<string> endpoints, List<string> notes)
        {
            var local = new Dictionary<string, string>();
            foreach (var t in LocalAddresses()) if (t.Item3 == "Up" && !local.ContainsKey(t.Item1)) local[t.Item1] = t.Item2;
            foreach (var ep in endpoints)
            {
                string why; var who = ArenaClient.WhoAmI(ep, 8, out why);
                if (who == null) { notes.Add("Registry lookup at " + ep + ": " + why + "."); continue; }
                var address = Json.Str(who, "address"); var service = Json.Str(who, "service_id");
                if (address == null || !local.ContainsKey(address)) { notes.Add("The event service sees this computer as " + address + ", which is not one of its own addresses; registry lookup not used."); break; }
                var list = new List<Candidate>();
                object ds; who.TryGetValue("displays", out ds);
                var items = ds as System.Collections.IEnumerable;
                if (items != null)
                    foreach (var o in items)
                    {
                        var d = o as Dictionary<string, object>; if (d == null) continue;
                        list.Add(new Candidate { Address = address, Interface = local[address], DisplayId = Json.Str(d, "display_id"), Role = Json.Str(d, "kind"),
                                                 Reason = "registered at the event service " + service + " for " + address });
                    }
                if (list.Count == 0)
                    notes.Add("The event service " + service + " has no display registered at " + address + ". On the coordinator register it first: " +
                              "'admin head-add " + address + "' for a head, or 'admin orchestrator-display-add <display_id> orch:<app>/<orchestrator> --address " + address + "' for an orchestrator display.");
                return list;   // when the registry answers, it is authoritative: nothing is guessed
            }
            var fallback = Candidates(config);
            if (fallback.Count > 0) notes.Add("Identity proposed from the package's network convention because the registry could not be asked.");
            return fallback;
        }
    }

